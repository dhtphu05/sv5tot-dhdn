/**
 * Returns only the report definitions that the current StaffUser has permission to view/export
 * (Sections 2, 81, 82, 113)
 */
export function getAuthorizedReportDefinitions(
  user: StaffUser
): ReportDefinition[] {
  const canSeeUnpublished = canInspectUnpublishedResults(user);
  return REPORT_DEFINITIONS.filter((def) => {
    if (!hasAnyCapability(user, def.requiredCapabilities)) return false;
    if (def.requiresUnpublishedResultAccess && !canSeeUnpublished) return false;
    return true;
  });
}
